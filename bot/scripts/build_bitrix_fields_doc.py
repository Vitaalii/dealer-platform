def M(*pairs):
    """M(['1К','1Т'], 'Б↻', '2', 'T?') → {col: mark}"""
    out = {}
    for i in range(0, len(pairs), 2):
        cols, mark = pairs[i], pairs[i + 1]
        for c in ([cols] if isinstance(cols, str) else cols):
            out[c] = mark
    return out


